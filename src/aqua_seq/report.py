def build_headline_block() -> str:
    """Assemble the short answer-first block that opens the README."""
    final = _read_json("final_evaluation")
    model = final["final_model_test_at_chosen_threshold"]
    dummy = final["dummy_baseline_test"]
    rule = final["rule_baseline_test"]
    cis = final["final_model_test_bootstrap_ci_95"]
    total_unsafe = model["true_positives"] + model["false_negatives"]
    tests_saved = dummy["flag_rate"] - model["flag_rate"]

    return "\n".join(
        [
            HEADLINE_BEGIN,
            "",
            "## Summary",
            "",
            f"{final['best_model']} reaches "
            f"**ROC-AUC {model['roc_auc']:.3f}** ({_ci(cis, 'roc_auc')}) on a test set used "
            f"once. At the risk-aware threshold it catches "
            f"**{model['recall_unsafe']:.0%} of unsafe samples** at "
            f"**{model['precision_unsafe']:.0%} precision**, saving ~"
            f"**{tests_saved:.0%} of lab capacity** versus testing everything — and missing "
            f"**{model['false_negatives']} of {total_unsafe}** unsafe samples.",
            "",
            "| | Catches unsafe | Precision | Sends to lab |",
            "|---|---|---|---|",
            f"| **{final['best_model']}** (final) | {model['recall_unsafe']:.0%} | "
            f"{model['precision_unsafe']:.0%} | {model['flag_rate']:.0%} |",
            f"| Guideline rule (WHO/BIS/EPA) | {rule['recall_unsafe']:.0%} | "
            f"{rule['precision_unsafe']:.0%} | {rule['flag_rate']:.0%} |",
            f"| Test everything (dummy) | {dummy['recall_unsafe']:.0%} | "
            f"{dummy['precision_unsafe']:.0%} | {dummy['flag_rate']:.0%} |",
            "",
            HEADLINE_END,
        ]
    )


def build_compact_block() -> str:
    """Assemble the condensed results block used in the README.

    The exhaustive version is written to ``results/metrics/readme_sections.md`` so the
    README can stay short without the detail being lost.
    """
    final = _read_json("final_evaluation")
    audit = _read_json("data_audit")
    meta = _read_json("run_metadata")
    model = final["final_model_test_at_chosen_threshold"]
    cis = final["final_model_test_bootstrap_ci_95"]
    choice = final["threshold_choice"]
    leaderboard = _read_csv("model_leaderboard")

    # Test metrics exist only for the final model and the two baselines: every other
    # candidate was selected on cross-validation alone and never scored on the test set.
    tested = {
        final["best_model"]: model,
        "Guideline rule baseline": final["rule_baseline_test"],
        "Dummy (majority class)": final["dummy_baseline_test"],
    }

    rows = []
    for _, row in leaderboard.iterrows():
        name = row["model"]
        label = f"{name}{' **(final)**' if name == final['best_model'] else ''}"
        test = tested.get(name)
        if test is None:
            cells = "— | — | —"
        else:
            cells = (
                f"{_fmt(test['roc_auc'])} | {_fmt(test['recall_unsafe'])} | "
                f"{_fmt(test['precision_unsafe'])}"
            )
        rows.append(
            f"| {label} | {_fmt(row['cv_roc_auc_mean'])} ± "
            f"{_fmt(row['cv_roc_auc_std'])} | {cells} |"
        )

    return "\n".join(
        [
            BEGIN_MARKER,
            "",
            f"{audit['n_rows']:,} samples, {audit['unsafe_prevalence']:.1%} unsafe. "
            f"Cross-validated on the training set (5-fold × 3); test set "
            f"({final['n_test']:,} samples) scored once at threshold "
            f"{choice['threshold']:.3f}.",
            "",
            "| Model | CV ROC-AUC | Test ROC-AUC | Recall | Precision |",
            "|---|---|---|---|---|",
            *rows,
            "",
            f"95% CI ({config.N_BOOTSTRAP:,}-resample bootstrap) for the final model: "
            f"ROC-AUC {_ci(cis, 'roc_auc')}, PR-AUC {_fmt(model['pr_auc'])} "
            f"{_ci(cis, 'pr_auc')}, recall {_ci(cis, 'recall_unsafe')}, "
            f"precision {_ci(cis, 'precision_unsafe')}.",
            "",
            f"*Full tables in "
            f"[`results/metrics/readme_sections.md`](results/metrics/readme_sections.md) — "
            f"hyperparameters, guideline limits, imputer comparison, feature importance, "
            f"error profiles. Runtime {meta['runtime_seconds'] / 60:.0f} min, seed "
            f"`{meta['random_seed']}`.*",
            "",
            END_MARKER,
        ]
    )


def _inject(text: str, begin: str, end: str, block: str) -> str:
    """Replace the content between two markers, leaving the rest of the text intact."""
    if begin in text and end in text:
        return text.split(begin)[0] + block + text.split(end)[1]
    return text


def build_readme_sections(readme_path: Path | None = None) -> Path:
    """Write the results block and inject it into the README between markers.

    Both the opening headline block and the full results block are regenerated, so no
    number anywhere in the README can drift away from the saved results files.

    Args:
        readme_path: Override for the README location.

    Returns:
        Path of the standalone results markdown file.
    """
    block = build_results_block()
    standalone = config.METRICS_DIR / "readme_sections.md"
    standalone.write_text(block, encoding="utf-8")

    readme = readme_path or (config.PROJECT_ROOT / "README.md")
    if readme.exists():
        text = readme.read_text(encoding="utf-8")
        text = _inject(text, HEADLINE_BEGIN, HEADLINE_END, build_headline_block())
        text = _inject(text, BEGIN_MARKER, END_MARKER, build_compact_block())
        readme.write_text(text, encoding="utf-8")
    return standalone
