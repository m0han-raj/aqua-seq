        "",
        "*Cross-validated on the training set only, 5-fold × 3 repeats. "
        "Hyperparameters were searched with "
        f"{config.N_SEARCH_ITER}-candidate randomised search over 5-fold CV; the imputation "
        "strategy was part of that search.*",
        "",
        "### Final model vs. baselines on the held-out test set",
        "",
        build_headline_table(),
        "",
        "*The test set was used exactly once, for this table. Confidence intervals are "
        f"{config.N_BOOTSTRAP:,}-resample bootstrap percentile intervals.*",
        "",
        "### The chosen decision threshold",
        "",
        build_threshold_section(),
        "",
