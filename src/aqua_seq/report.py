"""Build the README results sections from the saved results files.

Nothing here invents a number. Every value is read back from ``results/metrics``,
so the README cannot drift away from what the code actually produced. The rendered
block is injected into ``README.md`` between the AUTOGENERATED markers.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

from . import config

BEGIN_MARKER = "<!-- BEGIN:AUTOGENERATED-RESULTS -->"
END_MARKER = "<!-- END:AUTOGENERATED-RESULTS -->"
HEADLINE_BEGIN = "<!-- BEGIN:AUTOGENERATED-HEADLINE -->"
HEADLINE_END = "<!-- END:AUTOGENERATED-HEADLINE -->"


def _read_json(name: str) -> dict[str, Any]:
    """Read a metrics JSON file by stem."""
    path = config.METRICS_DIR / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8"))


def _read_csv(name: str) -> pd.DataFrame:
    """Read a metrics CSV file by stem."""
    return pd.read_csv(config.METRICS_DIR / f"{name}.csv")


def _fmt(value: float | None, digits: int = 3) -> str:
    """Format a float for a markdown table, or an em dash when absent."""
    if value is None or pd.isna(value):
        return "—"
    return f"{value:.{digits}f}"


def _ci(cis: dict[str, dict[str, float]], metric: str) -> str:
    """Render a bootstrap confidence interval as ``[lo, hi]``."""
    if metric not in cis:
        return "—"
    return f"[{cis[metric]['lower']:.3f}, {cis[metric]['upper']:.3f}]"


def build_model_table() -> str:
    """Render the model/baseline leaderboard as a markdown table."""
    leaderboard = _read_csv("model_leaderboard")
    final = _read_json("final_evaluation")
    best = final["best_model"]

    lines = [
        "| Model | Type | CV ROC-AUC (5×3, train) | Imputer chosen by CV |",
        "|---|---|---|---|",
    ]
    for _, row in leaderboard.iterrows():
        marker = " **(final)**" if row["model"] == best else ""
        imputer = row.get("chosen_imputer")
        indicator = row.get("chosen_imputer_add_indicator")
        if pd.isna(imputer) if not isinstance(imputer, str) else False:
            imputer_text = "—"
        elif isinstance(imputer, str):
            imputer_text = imputer + (" + indicators" if indicator is True else "")
        else:
            imputer_text = "—"
        lines.append(
            f"| {row['model']}{marker} | {row['kind']} | "
            f"{_fmt(row['cv_roc_auc_mean'])} ± {_fmt(row['cv_roc_auc_std'])} | {imputer_text} |"
        )
    return "\n".join(lines)


def build_headline_table() -> str:
    """Render the final test-set comparison against both baselines."""
    final = _read_json("final_evaluation")
    model = final["final_model_test_at_chosen_threshold"]
    cis = final["final_model_test_bootstrap_ci_95"]
    rule = final["rule_baseline_test"]
    dummy = final["dummy_baseline_test"]
    best = final["best_model"]
    threshold = final["threshold_choice"]["threshold"]

    header = (
        "| Metric (UNSAFE = positive) | "
        f"**{best} @ thr {threshold:.3f}** | 95% CI (bootstrap) | "
        "Guideline rule baseline | Dummy (majority class) |"
    )
    lines = [header, "|---|---|---|---|---|"]
    rows = [
        ("ROC-AUC", "roc_auc", True),
        ("PR-AUC (average precision)", "pr_auc", True),
        ("Recall on UNSAFE", "recall_unsafe", True),
        ("Precision on UNSAFE", "precision_unsafe", True),
        ("F1 on UNSAFE", "f1_unsafe", True),
        ("Balanced accuracy", "balanced_accuracy", True),
        ("Share of samples flagged for lab testing", "flag_rate", False),
    ]
    for label, key, has_ci in rows:
        lines.append(
            f"| {label} | {_fmt(model.get(key))} | "
            f"{_ci(cis, key) if has_ci else '—'} | "
            f"{_fmt(rule.get(key))} | {_fmt(dummy.get(key))} |"
        )
    lines.append(
        f"| Unsafe samples missed (false negatives) | {model['false_negatives']} | — | "
        f"{rule['false_negatives']} | {dummy['false_negatives']} |"
    )
    lines.append(
        f"| Test samples | {model['n_samples']} | — | "
        f"{rule['n_samples']} | {dummy['n_samples']} |"
    )
    return "\n".join(lines)


def build_threshold_section() -> str:
    """Describe the chosen operating threshold and the cost of the trade-off."""
    final = _read_json("final_evaluation")
    choice = final["threshold_choice"]
    chosen = final["final_model_test_at_chosen_threshold"]
    default = final["final_model_test_at_default_threshold"]

    met = "reached" if choice["target_met"] else "**NOT reachable**"
    extra_flags = chosen["flag_rate"] - default["flag_rate"]
    extra_recall = chosen["recall_unsafe"] - default["recall_unsafe"]

    return "\n".join(
        [
            f"The operating threshold was chosen on **cross-validated predictions over the "
            f"training set only** (the test set was untouched at this point). Among all "
            f"thresholds reaching at least **{choice['target_recall']:.0%} recall on the "
            f"UNSAFE class**, we keep the one with the highest precision.",
            "",
            f"- Recall target of {choice['target_recall']:.0%} was {met} in cross-validation.",
            f"- **Chosen threshold: {choice['threshold']:.4f}** on predicted P(UNSAFE) "
            f"(cross-validated recall {choice['achieved_recall']:.3f}, "
            f"precision {choice['achieved_precision']:.3f}).",
            "",
            "**What the trade-off costs, measured on the test set:**",
            "",
            "| | Default threshold 0.5 | Chosen threshold " f"{choice['threshold']:.3f} | Change |",
            "|---|---|---|---|",
            f"| Recall on UNSAFE | {_fmt(default['recall_unsafe'])} | "
            f"{_fmt(chosen['recall_unsafe'])} | {extra_recall:+.3f} |",
            f"| Precision on UNSAFE | {_fmt(default['precision_unsafe'])} | "
            f"{_fmt(chosen['precision_unsafe'])} | "
            f"{chosen['precision_unsafe'] - default['precision_unsafe']:+.3f} |",
            f"| Unsafe samples missed | {default['false_negatives']} | "
            f"{chosen['false_negatives']} | "
            f"{chosen['false_negatives'] - default['false_negatives']:+d} |",
            f"| Safe samples sent for testing anyway | {default['false_positives']} | "
            f"{chosen['false_positives']} | "
            f"{chosen['false_positives'] - default['false_positives']:+d} |",
            f"| Share of all samples flagged | {_fmt(default['flag_rate'])} | "
            f"{_fmt(chosen['flag_rate'])} | {extra_flags:+.3f} |",
            "",
            f"In plain terms: moving from the default cut-off to the risk-aware one "
            f"catches **{chosen['true_positives'] - default['true_positives']} more unsafe "
            f"samples** out of {chosen['true_positives'] + chosen['false_negatives']} in the "
            f"test set, at the cost of sending "
            f"**{chosen['false_positives'] - default['false_positives']} more safe samples** "
            f"to the lab.",
        ]
    )


def build_rule_table() -> str:
    """Render the verified guideline limits actually used by the rule baseline."""
    rule = _read_json("rule_baseline")
    lines = [
        "| Parameter | Limit applied | Source | Rows breaching |",
        "|---|---|---|---|",
    ]
    for name, info in rule["parameters_used"].items():
        if info["lower"] is not None and info["upper"] is not None:
            limit = f"{info['lower']}–{info['upper']} {info['unit']}"
        elif info["upper"] is not None:
            limit = f"≤ {info['upper']} {info['unit']}"
        else:
            limit = f"≥ {info['lower']} {info['unit']}"
        lines.append(
            f"| `{name}` | {limit} | {info['source']} | "
            f"{info['n_violations']:,} ({info['pct_violations']:.1f}%) |"
        )
    lines.append("")
    lines.append("**Excluded from the rule — no numeric limit could be verified:**")
    lines.append("")
    for name, reason in rule["parameters_excluded"].items():
        lines.append(f"- `{name}` — {reason}")
    return "\n".join(lines)


def build_imputer_table() -> str:
    """Render the cross-validated imputation strategy comparison."""
    frame = _read_csv("imputer_comparison")
    lines = ["| Imputation strategy | CV ROC-AUC (train) |", "|---|---|"]
    for _, row in frame.iterrows():
        lines.append(
            f"| `{row['imputer']}` | {_fmt(row['cv_roc_auc_mean'])} ± "
            f"{_fmt(row['cv_roc_auc_std'])} |"
        )
    return "\n".join(lines)


def build_importance_table() -> str:
    """Render permutation importance for the final model."""
    frame = _read_csv("permutation_importance")
    lines = [
        "| Feature | Drop in test ROC-AUC when shuffled | In the guideline rule? |",
        "|---|---|---|",
    ]
    for _, row in frame.iterrows():
        in_rule = "yes" if row["feature"] in config.PARAMETER_LIMITS else "no (unverified limit)"
        lines.append(
            f"| `{row['feature']}` | {row['importance_mean']:.4f} ± "
            f"{row['importance_std']:.4f} | {in_rule} |"
        )
    return "\n".join(lines)


def build_dataset_table() -> str:
    """Render the dataset audit summary."""
    audit = _read_json("data_audit")
    missing = audit["missingness"]
    lines = [
        "| Feature | Unit | Missing | % missing |",
        "|---|---|---|---|",
    ]
    for name in config.FEATURES:
        info = missing.get(name, {"n_missing": 0, "pct_missing": 0.0})
        lines.append(
            f"| `{name}` | {config.FEATURE_UNITS[name]} | {int(info['n_missing']):,} | "
            f"{info['pct_missing']:.1f}% |"
        )
    lines.append(
        f"| `{config.RAW_TARGET}` (target) "
        "| 1 = potable (SAFE), 0 = not potable (UNSAFE) | 0 | 0.0% |"
    )
    return "\n".join(lines)


def build_error_profile_table() -> str:
    """Compare median feature values for missed vs. caught unsafe samples."""
    frame = _read_csv("error_analysis_missed_vs_caught")
    frame = frame.assign(
        relative_gap=lambda d: (d["median_gap"] / d["median_caught_unsafe"]).abs()
    ).sort_values("relative_gap", ascending=False)
    lines = [
        "| Parameter | Median (missed unsafe) | Median (caught unsafe) | Relative difference |",
        "|---|---|---|---|",
    ]
    for _, row in frame.iterrows():
        lines.append(
            f"| `{row['feature']}` | {row['median_missed_unsafe']:.3g} | "
            f"{row['median_caught_unsafe']:.3g} | {row['relative_gap']:.1%} |"
        )
    return "\n".join(lines)


def _largest_error_gap() -> str:
    """Describe the single largest relative median gap between missed and caught."""
    frame = _read_csv("error_analysis_missed_vs_caught")
    frame = frame.assign(
        relative_gap=lambda d: (d["median_gap"] / d["median_caught_unsafe"]).abs()
    ).sort_values("relative_gap", ascending=False)
    top = frame.iloc[0]
    return f"`{top['feature']}` at {top['relative_gap']:.1%}"


